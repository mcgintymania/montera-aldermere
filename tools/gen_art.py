#!/usr/bin/env python3
"""Writes src/artdata.js from tools/artspec.py plus each Wildmon's colours."""
import json, subprocess, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root / 'tools'))
from artspec import SPEC
base = json.loads((root / 'tools' / 'artbase.json').read_text())
lines = ["'use strict';", '/* Wildmon looks: body form, parts and colours (generated by tools/gen_art.py from tools/artspec.py) */', 'Object.assign(DATA.artBook = {}, {']
for sp, colours in base.items():
    if sp not in SPEC: raise SystemExit(f'no art spec for {sp}')
    spec = dict(SPEC[sp]); mul = spec.pop('s_mul', 1)
    art = {'f': spec.pop('f')}
    art.update({k: colours[k] for k in ('c', 'c2', 'b', 'eye') if k in colours})
    art['s'] = round(colours.get('s', 1) * mul, 3)
    for k, v in colours.items():
        if k in ('beak', 'flame', 'leg', 'stripe', 'petal', 'fist', 'plume') and k not in spec: art[k] = v
    art.update(spec)
    lines.append(f'  {sp}: {json.dumps(art, separators=(", ", ": "))},')
lines += ['});', 'for (const [id, art] of Object.entries(DATA.artBook)) if (DATA.species[id]) DATA.species[id].art = art;', '']
(root / 'src' / 'artdata.js').write_text('\n'.join(lines))
print('wrote', len(base), 'looks')
